/** A project with two regions, plus the corpus-level files the builder leaves at the regions root. */
function projectWithRegions(): { project: string; regions: string } {
  const project = tempDir('regions-project');
  const regions = join(project, '.foundry', 'regions');
  write(
    join(regions, 'concurrency-locks', 'region.json'),
    JSON.stringify({
      id: 'concurrency-locks',
      title: 'Concurrency, locks and lanes',
      routing: LOCKS_ROUTING,
      concepts: ['locks', 'supersede-lanes'],
      tokens: 12385,
      tokenMethod: 'chars/4',
      sources: { docs: ['docs/claude/CONCURRENCY.md'] },
    }),
  );
  write(
    join(regions, 'concurrency-locks', 'knowledge.md'),
    knowledge('Concurrency, locks and lanes', LOCKS_ROUTING, DEEP_FACT),
  );
  write(
    join(regions, 'lens-model', 'region.json'),
    JSON.stringify({
      id: 'lens-model',
      title: 'The lens model',
      routing: 'Is this about what a json-rules lens is and how its layers compose?',
      concepts: ['lib-json-rules-lens'],
    }),
  );
  write(
    join(regions, 'lens-model', 'knowledge.md'),
    knowledge('The lens model', 'Is this about a lens?', 'DEEP_FACT_LENS: layers only narrow.'),
  );
  write(join(regions, 'registry.json'), JSON.stringify({ version: 1, regions: [] }));
  write(join(regions, 'GLOSSARY.md'), 'CORPUS_GLOSSARY: never composed into one Warden.');
  write(join(regions, 'ERRORS.md'), 'CORPUS_ERRORS: never composed into one Warden.');
  return { project, regions };
}

