test('under wardens: regions a project runs one generated Warden per region, from region.json', () => {
  const { project, regions } = projectWithRegions();
  const c = config(project);
  validateConfig(c);
  const view = resolveProjectView(c, 'P')!;
  expect(view.wardens).toMatchObject({
    mode: 'regions',
    requested: 'regions',
    regionsDir: regions,
  });
  expect(view.wardens.regions!.map((r) => r.id)).toEqual(['concurrency-locks', 'lens-model']);
  expect(view.config.wardens).toBe('regions');

  // The roster is exactly the regions: the hand-named Warden is not this project's Warden.
  expect(configuredExperts(view.config).experts.map((e) => e.domain)).toEqual([
    'concurrency-locks',
    'lens-model',
  ]);
  expect(view.config.agents['librarian-reuse']).toBeUndefined();
  expect(view.config.agents.worker).toEqual(c.agents.worker!);

  const locks = view.config.agents['concurrency-locks']!;
  expect(locks).toMatchObject({
    id: 'concurrency-locks',
    kind: 'domain-librarian',
    flowRole: 'domain-advising',
    domain: 'concurrency-locks',
    description: 'Concurrency, locks and lanes',
    invocation: 'always',
    guardTriggers: [...REGION_GUARD_TRIGGERS],
    domainKnowledge: [regionSourceId('concurrency-locks')],
    enabled: true,
  });
  expect(REGION_GUARD_TRIGGERS).toEqual(
    expect.arrayContaining(['Write', 'Edit', 'Bash', 'file_write', 'bash']),
  );
  expect(locks.prompt).toStartWith(REGION_WARDEN_INSTRUCTIONS);
  expect(locks.prompt).toContain('Your region: Concurrency, locks and lanes (`concurrency-locks`)');
  expect(locks.prompt).toContain(`Routing: ${LOCKS_ROUTING}`);
  // Its knowledge is the region's knowledge.md through a markdown source (audited as source content).
  expect(view.config.sources[regionSourceId('concurrency-locks')]).toEqual({
    id: 'region:concurrency-locks',
    label: 'Concurrency, locks and lanes (region knowledge)',
    type: 'markdown',
    uri: join(regions, 'concurrency-locks', 'knowledge.md'),
    enabled: true,
  });
  // Provenance: every field derived from the region, and the view's project carries the agent.
  const resolved = view.agents.find((a) => a.id === 'concurrency-locks')!;
  expect(resolved).toMatchObject({
    scope: 'project-generated',
    generatedFrom: join(regions, 'concurrency-locks', 'region.json'),
  });
  expect(resolved.fields.prompt).toMatchObject({ origin: 'project', strategy: 'generated' });
  expect(resolved.fields.prompt!.chunks![0]!.from).toBe(
    join(regions, 'concurrency-locks', 'region.json'),
  );
  expect(view.config.projects.P!.agents!['concurrency-locks']).toEqual(locks);
  expect(view.agents.some((a) => a.id === 'librarian-reuse')).toBe(false);
  // Its instructions read no general files (CLAUDE.md and the like); the region is its knowledge.
  expect(view.config.composition!.roles!['concurrency-locks']).toEqual({
    instructions: { general: [] },
  });
  // A role entry in settings for the region still wins, field by field.
  c.composition!.roles = {
    'lens-model': { budget: 50_000, instructions: { general: ['project'] } },
  };
  const tuned = resolveProjectView(c, 'P')!.config.composition!.roles!;
  expect(tuned['lens-model']).toEqual({ budget: 50_000, instructions: { general: ['project'] } });
  expect(tuned['concurrency-locks']).toEqual({ instructions: { general: [] } });
});

test('the default is the hand-named roster; regions asked for without a regions directory says so and keeps the roster', () => {
  const { project } = projectWithRegions();
  const c = config(project);
  delete c.wardens;
  validateConfig(c);
  const byDefault = resolveProjectView(c, 'P')!;
  expect(byDefault.wardens).toEqual({ mode: 'roster', requested: 'roster' });
  expect(byDefault.config.wardens).toBe('roster');
  expect(configuredExperts(byDefault.config).experts.map((e) => e.domain)).toEqual(['reuse']);
  expect(byDefault.agents.map((a) => a.scope)).not.toContain('project-generated');

  // A project may opt in on its own.
  c.projects.P!.wardens = 'regions';
  validateConfig(c);
  expect(resolveProjectView(c, 'P')!.wardens.mode).toBe('regions');

  // Regions asked for, none there: the roster runs, and the view says why.
  const empty = tempDir('no-regions');
  c.projects.Q = { id: 'Q', path: empty, wardens: 'regions' };
  validateConfig(c);
  const q = resolveProjectView(c, 'Q')!;
  expect(q.wardens).toMatchObject({ mode: 'roster', requested: 'regions' });
  expect(q.wardens.reason).toContain(`no regions at ${join(empty, '.foundry', 'regions')}`);
  expect(q.config.wardens).toBe('roster');
  expect(configuredExperts(q.config).experts.map((e) => e.domain)).toEqual(['reuse']);

  // `regions` points the project at another directory, absolute or relative to it.
  const elsewhere = tempDir('regions-elsewhere');
  write(
    join(elsewhere, 'only', 'region.json'),
    JSON.stringify({ id: 'only', title: 'Only', routing: 'Is this about the only thing?' }),
  );
  write(join(elsewhere, 'only', 'knowledge.md'), '# Only\n\nONLY_KNOWLEDGE.');
  c.projects.Q!.regions = elsewhere;
  expect(regionsDirectory(c.projects.Q!)).toBe(elsewhere);
  expect(resolveProjectView(c, 'Q')!.wardens.regions!.map((r) => r.id)).toEqual(['only']);
  c.projects.Q = {
    id: 'Q',
    path: project,
    wardens: 'regions',
    regions: 'docs/../.foundry/regions',
  };
  expect(resolveProjectView(c, 'Q')!.wardens.regions!.length).toBe(2);

  for (const bad of ['always', 'regions ', 1]) {
    c.wardens = bad as never;
    expect(() => validateConfig(c)).toThrow('wardens must be "roster" or "regions"');
  }
});

