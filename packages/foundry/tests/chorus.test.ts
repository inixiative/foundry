interface Call {
  phase: 'central' | 'pre' | 'post' | 'route';
  messages: LLMMessage[];
  opts: CompletionOpts;
}

/** A thread whose Warden says one pointer, as a live thread composes and delivers it. */
function setup(c: FoundryConfig, pointer: string) {
  const calls: Call[] = [];
  const provider = (id: string): LLMProvider => ({
    id,
    async complete(messages, opts = {}) {
      const phase: Call['phase'] = opts.threadId?.endsWith(':cartographer')
        ? 'route'
        : opts.threadId?.includes(':review:')
          ? 'post'
          : opts.threadId?.includes(':aux:')
            ? 'pre'
            : 'central';
      calls.push({ phase, messages: structuredClone(messages), opts: { ...opts } });
      return {
        model: 'controlled',
        content:
          phase === 'central'
            ? 'done'
            : phase === 'route'
              ? JSON.stringify({ layers: [], domains: [], confidence: 1 })
              : phase === 'pre'
                ? opts.threadId?.includes('domain:concurrency-locks')
                  ? JSON.stringify({ layers: [], snippets: [pointer], confidence: 0.9 })
                  : 'NO_COMMENT'
                : 'NO_COMMENT',
      };
    },
  });
  const central = provider('central'),
    flow = provider('flow');
  const providers = new Map([central, flow].map((p) => [p.id, p]));
  const sourceResolver = createSourceResolver({
    memory: new FileMemory(join(tempDir('memory'), 'm')),
  });
  const stack = new ContextStack(buildLayers(c, { sourceResolver }));
  const manager = new ThreadRuntimeManager({
    config: c,
    llm: flow,
    providers,
    log() {},
    warn() {},
    learning: { timeoutMs: 20, hardTimeoutMs: 1000 },
  });
  managers.push(manager);
  const deps = { provider: central, providers };
  const factory = new ThreadFactory({
    stack,
    agents: buildAgents(c, stack, deps),
    runtime: manager,
    configuration: { config: c, layers: { sourceResolver }, agents: deps },
  });
  const all = (phase: Call['phase']) => calls.filter((call) => call.phase === phase);
  return { factory, manager, calls, all };
}

